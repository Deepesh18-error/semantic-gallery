"""Boundaries used by the desktop catalog and future indexing worker."""
from typing import Protocol, Sequence


class CatalogStore(Protocol):
    def put_collection(self, *, collection_id: str, user_id: str, name: str, **metadata): ...
    def put_file(self, *, file_id: str, user_id: str, source_id: str, path: str,
                 source_type: str, mime_type: str, fingerprint: str = "", **metadata): ...
    def get_file(self, file_id: str, user_id: str): ...
    def list_files(self, user_id: str, collection_id: str | None = None): ...


class FullTextStore(Protocol):
    def search(self, query: str, *, user_id: str, collection_id: str | None = None,
               source_type: str | None = None, limit: int = 20): ...


class VectorStore(Protocol):
    def upsert(self, *, vector_id: str, segment_id: int, values: Sequence[float],
               model_config: str, generation: int = 1): ...
    def query(self, values: Sequence[float], *, user_id: str, model_config: str,
              collection_id: str | None = None, source_type: str | None = None,
              limit: int = 20): ...
    def delete(self, vector_id: str): ...


class EmbeddingProvider(Protocol):
    def embed_query(self, text: str) -> Sequence[float]: ...
    def embed_segment(self, segment) -> Sequence[float]: ...


class Extractor(Protocol):
    def extract(self, file_path: str, source_type: str) -> Sequence[dict]: ...


class JobScheduler(Protocol):
    def enqueue(self, file_version_id: int, stage: str) -> str: ...
    def claim(self, owner: str, lease_seconds: int = 300): ...
    def set_progress(self, job_id: str, owner: str, done: int, total: int): ...
    def renew(self, job_id: str, owner: str, lease_seconds: int = 300): ...
    def finish(self, job_id: str, owner: str, *, error: str = "", retry_seconds: int = 0): ...
